create table if not exists public.carts (
  user_id uuid primary key references auth.users(id) on delete cascade,
  items jsonb not null default '[]'::jsonb check(jsonb_typeof(items)='array'),
  updated_at timestamptz not null default now()
);
create table if not exists public.orders (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null references auth.users(id) on delete restrict,
  customer_name text not null,
  phone text not null,
  delivery_point text not null,
  note text not null default '',
  delivery_method text not null check(delivery_method in ('Cash on delivery','UPI on delivery','Razorpay')),
  total integer not null check(total >= 0),
  status text not null default 'received' check(status in ('payment_pending','received','packing','out_for_delivery','delivered','cancelled')),
  payment_status text not null default 'unpaid' check(payment_status in ('pending','unpaid','paid','failed')),
  razorpay_order_id text unique,
  razorpay_payment_id text unique,
  created_at timestamptz not null default now()
);
create table if not exists public.order_items (
  id bigint generated always as identity primary key,
  order_id uuid not null references public.orders(id) on delete cascade,
  product_index integer not null,
  quantity integer not null check(quantity between 1 and 20),
  unit_price integer not null check(unit_price >= 0)
);

alter table public.profiles enable row level security;
alter table public.products enable row level security;
alter table public.carts enable row level security;
alter table public.orders enable row level security;
alter table public.order_items enable row level security;
drop policy if exists "Profiles are readable by their owner" on public.profiles;
create policy "Profiles are readable by their owner" on public.profiles for select to authenticated using(user_id=auth.uid());
drop policy if exists "Profiles are editable by their owner" on public.profiles;
create policy "Profiles are editable by their owner" on public.profiles for update to authenticated using(user_id=auth.uid()) with check(user_id=auth.uid() and role='customer');
drop policy if exists "Active products are public" on public.products;
create policy "Active products are public" on public.products for select to anon,authenticated using(active);
drop policy if exists "Users manage own cart" on public.carts;
create policy "Users manage own cart" on public.carts for all to authenticated using(user_id=auth.uid()) with check(user_id=auth.uid());
drop policy if exists "Users read own orders" on public.orders;
create policy "Users read own orders" on public.orders for select to authenticated using(user_id=auth.uid());
drop policy if exists "Users create own orders" on public.orders;
drop policy if exists "Users update own orders" on public.orders;
drop policy if exists "Users read own order items" on public.order_items;
create policy "Users read own order items" on public.order_items for select to authenticated using(exists(select 1 from public.orders o where o.id=order_id and o.user_id=auth.uid()));
drop policy if exists "Users insert own order items" on public.order_items;

grant usage on schema public to anon,authenticated;
